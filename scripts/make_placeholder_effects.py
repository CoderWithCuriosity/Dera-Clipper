def _ffmpeg() -> str:
    import imageio_ffmpeg

    return imageio_ffmpeg.get_ffmpeg_exe()


def _make(ff: str, out: Path, entry: dict) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    if entry["kind"] == "sound":
        freq, seconds = entry["tone"]
        args = ["-f", "lavfi", "-i", f"sine=frequency={freq}:duration={seconds}",
                "-af", f"afade=t=out:st={max(0.0, seconds - 0.2):.2f}:d=0.2", str(out)]
    else:
        args = ["-f", "lavfi", "-i", f"color=c={entry['colour']}:size=640x360:rate=25:duration=3",
                "-pix_fmt", "yuv420p", "-c:v", "libx264", "-preset", "ultrafast", str(out)]
    subprocess.run([ff, "-hide_banner", "-loglevel", "error", "-y", *args], check=True)


def main() -> int:
    ff = _ffmpeg()
    for folder, theme in THEMES.items():
        base = EFFECTS / folder
        manifest_entries = []
        for entry in theme["effects"]:
            _make(ff, base / entry["file"], entry)
            manifest_entries.append({
                "file": entry["file"], "kind": entry["kind"], "tags": entry["tags"],
                "license": LICENSE, "source": SOURCE,
            })
        manifest = {"display_name": theme["display_name"], "description": theme["description"],
                    "effects": manifest_entries}
        (base / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"{theme['display_name']}: {len(manifest_entries)} effects")
    return 0


if __name__ == "__main__":
    sys.exit(main())
